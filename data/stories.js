/* =========================================================
   STORY FUNCTIONS
   ========================================================= */

function getStories() {

    return LINGO_STORIES;

}


function getStoryById(id) {

    return LINGO_STORIES.find(
        story => story.id === Number(id)
    );

}


function getStoriesByLevel(level) {

    return LINGO_STORIES.filter(
        story => story.level === level
    );

}


function getStoriesByCategory(category) {

    return LINGO_STORIES.filter(
        story => story.category === category
    );

}


function searchStories(searchTerm = "") {

    const term =
        searchTerm
            .toLowerCase()
            .trim();

    if (!term) {
        return LINGO_STORIES;
    }

    return LINGO_STORIES.filter(story => {

        const titles =
            Object.values(story.title)
                .join(" ")
                .toLowerCase();

        const texts =
            Object.values(story.text)
                .join(" ")
                .toLowerCase();

        return (
            titles.includes(term) ||
            texts.includes(term)
        );

    });

}


function getRandomStory() {

    if (!LINGO_STORIES.length) {
        return null;
    }

    return LINGO_STORIES[
        Math.floor(
            Math.random() *
            LINGO_STORIES.length
        )
    ];

}


function getStoryText(
    storyId,
    language
) {

    const story =
        getStoryById(storyId);

    if (!story) {
        return "";
    }

    return story.text[language] || "";
}


function getStoryTitle(
    storyId,
    language
) {

    const story =
        getStoryById(storyId);

    if (!story) {
        return "";
    }

    return story.title[language] || "";
}


/* =========================================================
   GLOBAL STORY API
   ========================================================= */

window.LingoStories = {

    all: LINGO_STORIES,

    get: getStories,

    getById: getStoryById,

    byLevel: getStoriesByLevel,

    byCategory: getStoriesByCategory,

    search: searchStories,

    random: getRandomStory,

    text: getStoryText,

    title: getStoryTitle,

    count: () =>
        LINGO_STORIES.length

};


