/* =========================================================
   CONVERT ARRAYS INTO OBJECTS
   ========================================================= */

Object.keys(LINGO_PHRASES).forEach(language => {

    LINGO_PHRASES[language] =
        LINGO_PHRASES[language].map(
            (phrase, index) => ({

                id:
                    `${language}-phrase-${index + 1}`,

                english:
                    phrase[0],

                phrase:
                    phrase[1],

                category:
                    phrase[2]

            })
        );

});


/* =========================================================
   PHRASE FUNCTIONS
   ========================================================= */

function getPhrases(language) {

    return LINGO_PHRASES[language] || [];

}


function getPhrasesByCategory(
    language,
    category
) {

    return getPhrases(language)
        .filter(
            phrase =>
                category === "all" ||
                phrase.category === category
        );

}


function searchPhrases(
    language,
    searchTerm = ""
) {

    const term =
        searchTerm
            .toLowerCase()
            .trim();

    if (!term) {
        return getPhrases(language);
    }

    return getPhrases(language)
        .filter(phrase =>
            phrase.english
                .toLowerCase()
                .includes(term) ||
            phrase.phrase
                .toLowerCase()
                .includes(term)
        );

}


function getRandomPhrase(language) {

    const phrases =
        getPhrases(language);

    if (!phrases.length) {
        return null;
    }

    return phrases[
        Math.floor(
            Math.random() *
            phrases.length
        )
    ];

}


function getTotalPhraseCount() {

    return Object.values(LINGO_PHRASES)
        .reduce(
            (total, phrases) =>
                total + phrases.length,
            0
        );

}


/* =========================================================
   GLOBAL API
   ========================================================= */

window.LingoPhrases = {

    all:
        LINGO_PHRASES,

    get:
        getPhrases,

    byCategory:
        getPhrasesByCategory,

    search:
        searchPhrases,

    random:
        getRandomPhrase,

    totalCount:
        getTotalPhraseCount

};


